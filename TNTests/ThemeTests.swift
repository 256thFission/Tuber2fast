import Foundation
import Testing
@testable import TNModel

/// The derivation, against the default-theme table in the design document.
///
/// The table is a transcription of the design canvas, and no single mix
/// reproduces it to the byte: several of its rows are not internally
/// consistent, so each channel is allowed to land within two of the value
/// written down. What is pinned exactly is the classification — which fills
/// are pale and which take the paper escape — because that is what a new
/// theme's chrome actually turns on.
@Suite("Macaron theme derivation")
struct ThemeTests {
    private let theme = Theme.macaron

    private func colour(_ hex: String) -> RGBA8 {
        RGBA8(hex: hex + "FF")!
    }

    private func near(_ produced: RGBA8, _ expected: String, _ what: String, within: Int = 2) {
        let want = colour(expected)
        for (made, wanted) in [
            (produced.red, want.red), (produced.green, want.green), (produced.blue, want.blue),
        ] {
            #expect(
                abs(Int(made) - Int(wanted)) <= within,
                "\(what): derived \(produced.hex), the table says \(want.hex)"
            )
        }
    }

    @Test("Every outline in the default-theme table falls out of the one mix rule")
    func outlineTable() {
        near(theme.outline(of: colour("#FF6A8C")), "#9B4558", "strawberry")
        near(theme.outline(of: colour("#FFB347")), "#9B6F30", "vanilla")
        near(theme.outline(of: Theme.pistachio), "#6E7763", "pistachio")
        near(theme.outline(of: colour("#FFFFFF")), "#7C7C7C", "white")
        near(theme.outline(of: colour("#5BA8E8")), "#3C698E", "sky ink")
    }

    @Test("Pale fills take 55 percent and saturated fills take 42")
    func paleness() {
        #expect(theme.isPale(colour("#FFFFFF")))
        #expect(theme.isPale(Theme.pistachio))
        #expect(theme.isPale(theme.ground))
        #expect(theme.isPale(theme.seatBody))
        #expect(!theme.isPale(theme.accent))
        #expect(!theme.isPale(theme.secondary))
        #expect(!theme.isPale(colour("#5BA8E8")))
        #expect(!theme.isPale(theme.ink))
    }

    @Test("The ink swatch gets an outline only because the paper escape flips the target")
    func paperEscape() {
        // Mixed toward the ink it already is, the ink swatch would have no
        // outline at all. The escape sends it to the paper instead.
        #expect(Theme.contrast(theme.ink, theme.ink) < Theme.threshold)
        let outline = theme.outline(of: theme.ink)
        #expect(Theme.contrast(outline, theme.ink) > 1.6)
    }

    @Test("The seat body is the accent most of the way to the paper")
    func seatBody() {
        #expect(theme.seatBody == Theme.mix(theme.accent, toward: theme.paper, 0.80))
        // The table's hex sits at about 83 percent; the document's rule says
        // 80, and the rule is what a new theme has to be generated by.
        near(theme.seatBody, "#FFE5EC", "seat body", within: 5)
    }

    @Test("The paper is white and the ground line is a step off the ground")
    func groundAndPaper() {
        #expect(theme.paper.hex == "#FFFFFFFF")
        // The document names no percentage for the grid line, only the hex
        // it lands on. What is held is the weight of the line, not its bytes.
        let tabled = Theme.contrast(RGBA8(hex: "#E6D9BEFF")!, theme.ground)
        #expect(abs(Theme.contrast(theme.ground2, theme.ground) - tabled) < 0.02)
        #expect(Theme.luminance(theme.ground2) < Theme.luminance(theme.ground))
    }

    @Test("Teenage Enamel's secondary is its ink, so it is the one token that escapes")
    func teenageEnamelEscape() {
        let enamel = Theme.teenageEnamel
        #expect(enamel.secondary == enamel.ink)
        near(enamel.outline(of: enamel.secondary), "#7A7A7A", "enamel secondary")
        for token in [enamel.ground, enamel.chrome, enamel.accent] {
            #expect(!escapes(enamel, token))
        }
        near(enamel.outline(of: enamel.accent), "#9F3C0B", "enamel accent")
    }

    @Test("Game Boy's purple escapes and its greens take the plain rule")
    func gameBoyEscape() {
        let boy = Theme.gameBoy
        // The plan expected the escape on the chrome and the ground. The
        // board's hexes put both greens well clear of the ink, so it fires
        // on the purple secondary instead.
        #expect(escapes(boy, boy.secondary))
        near(boy.outline(of: boy.secondary), "#A084BB", "game boy secondary")
        for token in [boy.ground, boy.chrome, boy.accent] {
            #expect(!escapes(boy, token))
        }
        near(boy.outline(of: boy.ground), "#60850F", "game boy ground")
        near(boy.outline(of: boy.chrome), "#798D66", "game boy chrome")
    }

    @Test("No preset ships a line its own fill can hide")
    func everyPresetDrawsAVisibleLine() {
        for preset in Theme.presets {
            let subject = preset.theme
            let tokens: [(String, RGBA8)] = [
                ("ground", subject.ground), ("chrome", subject.chrome), ("accent", subject.accent),
                ("secondary", subject.secondary), ("ink", subject.ink),
                ("paper", subject.paper), ("seat body", subject.seatBody),
            ]
            for (name, token) in tokens {
                let ratio = Theme.contrast(subject.outline(of: token), token)
                #expect(ratio >= 1.3, "\(preset.name)'s \(name) line is \(ratio) against its fill")
            }
        }
    }

    @Test("Every preset writes in seven colours, each of them readable on the paper")
    func everyPresetWritesInSevenReadableColours() {
        for preset in Theme.presets {
            let palette = preset.theme.palette
            #expect(palette.count == 7, "\(preset.name) offers \(palette.count) colours")
            #expect(
                Set(palette.map(\.hex)).count == palette.count,
                "\(preset.name) spends two of its seven slots on one colour"
            )
            // The threshold is the number the chrome already calls pale
            // against the paper, and a colour the paper cannot be told from
            // is a colour handwriting disappears into.
            for colour in palette {
                let ratio = Theme.contrast(colour, preset.theme.paper)
                #expect(ratio >= Theme.threshold, "\(preset.name)'s \(colour.hex) is \(ratio) on the paper")
            }
            // What people write in comes first, whatever else the theme
            // carries, so the bar's first swatch is never a decoration.
            let darkest = palette.min { Theme.luminance($0) < Theme.luminance($1) }
            #expect(palette.first == darkest, "\(preset.name) opens on a colour that is not its darkest")
        }
    }

    /// The escape is private, and what it does is public: an outline that
    /// came up off its fill instead of going down into it went the other
    /// way. The reverse for a theme whose mix is already inverted.
    ///
    /// It reads the escape off the direction, so it assumes no token is
    /// darker than its own theme's ink. That holds for all seven presets and
    /// is not a property the type enforces.
    private func escapes(_ theme: Theme, _ fill: RGBA8) -> Bool {
        let outline = Theme.luminance(theme.outline(of: fill))
        return theme.invertsMix ? outline < Theme.luminance(fill) : outline > Theme.luminance(fill)
    }

    @Test("Dark mode is the same rule with the target inverted, and the paper stays white")
    func inverted() {
        let dark = Theme(
            ground: colour("#26211B"),
            chrome: colour("#332C24"),
            accent: theme.accent,
            secondary: theme.secondary,
            ink: colour("#F4EADA"),
            palette: Theme.macaronDark.palette,
            invertsMix: true
        )
        #expect(dark.paper.hex == "#FFFFFFFF")
        // The chrome is dark, so its outline has to come up, not go down.
        #expect(Theme.luminance(dark.outline(of: dark.chrome)) > Theme.luminance(dark.chrome))
        // And the escape, which after dark runs to the ground: the ink is a
        // cream, so an outline mixed toward it would land on the ink itself.
        #expect(Theme.luminance(dark.outline(of: dark.ink)) < Theme.luminance(dark.ink))
    }
}
